type Messages = Record<keyof typeof en, string>;
type Lang = "en" | "zh";

const STORAGE_KEY = "qa-lang";

function detectLang(): Lang {
  const stored = localStorage.getItem(STORAGE_KEY);
  if (stored === "zh" || stored === "en") return stored;
  if (navigator.language.startsWith("zh")) return "zh";
  return "en";
}

function getMessages(lang: Lang): Messages {
  return lang === "zh" ? zh : en;
}

const I18nCtx = createContext<{
  t: Messages;
  lang: Lang;
  setLang: (lang: Lang) => void;
}>({ t: en, lang: "en", setLang: () => {} });

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(detectLang);
  const [messages, setMessages] = useState<Messages>(() => getMessages(lang));

  const setLang = useCallback((next: Lang) => {
    setLangState(next);
    setMessages(getMessages(next));
    localStorage.setItem(STORAGE_KEY, next);
    document.documentElement.lang = next;
  }, []);

  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);

  return (
    <I18nCtx.Provider value={{ t: messages, lang, setLang }}>
      {children}
    </I18nCtx.Provider>
  );
}

export function useI18n() { return useContext(I18nCtx); }
